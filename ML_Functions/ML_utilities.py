def Prepare_Features_GNN(
    dataset,
    gamma=10,
    ds_loading=0.0,
    Nsamples='all',
    ForceSplit=True,
    HopsFilter=1,
    Clf_threshold=0.0,
    clip_val=-1.0):
    """
    Prepare node, edge, and target-label features for GNN and FNN models.

    Input: X_pd [sample,bus],X_delta[sample,Bus], X_pg[sample,G], X_pinj[sample,bus] is injection
    X_pflow_list is a list of numpy arrays of flow values, based on the topology of the dataset
    y_pflow[sample,candidate_sw,line],
    Edge_sender_list/Edge_receiver_list: list of np vectors that contains the sender/receiver index of each sample

    X is array, x is vector

    ds_loading creates a discontinouty in the index.

    Output: a dictionary of node and edge features and lables to predict.
    node types: 'bus', --> HomoGNN means we only have one node type
    edge_type: 'line' for now.

    Parameters
    ----------
    dataset : dict
        Training dataset generated by the DC-OSS data-generation pipeline.
        It must contain flow, injection, topology, line-limit, candidate-node,
        and graph-connectivity information.
    gamma : float
        Exponent used in the congestion index.
    ds_loading : float
        Loading threshold used to activate the congestion index.
    Nsamples : int or str
        Number of samples to process. Currently kept for compatibility.
    ForceSplit : bool
        If False, negative congestion improvements are clipped to zero.
    HopsFilter : int
        Maximum hop distance from congestion for keeping candidate nodes.
    Clf_threshold : float
        Threshold used to convert regression labels into binary labels.
    clip_val : float
        Lower clipping value for regression targets.

    Returns
    -------
    Finaldict : dict
        Dictionary containing GNN/FNN features, regression labels,
        classification labels, graph connectivity, candidate-node indices,
        and prediction masks.
    """

    # Nline = len(networkdata['line'])
    # Bus=networkdata['Bus']
    # Nbus = len(Bus)

    # line_reactance = networkdata['branch1D']['x'].to_numpy()

    # === Load dataset arrays and lists
    X_pinj = dataset['X_pinj']
    X_pflow = dataset['X_pflow']
    X_pflow_list = dataset['X_pflow_list']
    y_pflow_list = dataset['y_pflow_list']
    Edge_sender_list = dataset['Edge_sender_list']
    Edge_receiver_list = dataset['Edge_receiver_list']
    line_outage_indices = dataset['line_outage_indices']
    bus_sw_indices_list = dataset['bus_sw_indices_list']
    X_node_degree = dataset['X_node_degree']
    line_limit_list = dataset['line_limit_list']
    hops_list = dataset['hops_list']

    # === Dataset dimensions
    Nbus = X_pinj.shape[1]
    line_reactance = dataset['HyperParameters']['line_reactance']
    Nline = len(line_reactance)

    Nsamples = X_pinj.shape[0]

    # print(f"{Nsamples} Samples!")

    # ==========================================================================
    # Bus/node features
    # ==========================================================================

    # create bus features
    N_bus_features = 3

    X_bus_feature = np.zeros((Nsamples, Nbus, N_bus_features))
    X_bus_feature[:, :, 0] = X_pinj                 # feature 0 is injection
    X_bus_feature[:, :, 1] = X_node_degree          # feature 1 is degree
    X_bus_feature[:, :, 2] = np.array(hops_list)    # hops away


    # ==========================================================================
    # Edge/line features for GNN models
    # ==========================================================================

    # create edge/line features
    N_line_features = 4

    X_line_feature_list = []   # a list of [Nline,N_line_features] #np.zeros((Nsamples,Nline,N_line_features))

    for sample in range(Nsamples):
        nl = Nline - len(line_outage_indices[sample])
        x_line_feature = np.zeros((nl, N_line_features))

        x_line_feature[:, 0] = X_pflow_list[sample]
        x_line_feature[:, 1] = X_pflow_list[sample] / line_limit_list[sample]     # ratio
        x_line_feature[:, 2] = line_limit_list[sample]                            # limit
        x_line_feature[:, 3] = np.delete(line_reactance, line_outage_indices[sample])   # reactance

        X_line_feature_list += [x_line_feature]

    # ==========================================================================
    # Fixed-size line features for FNN models
    # ==========================================================================

    # X_line_feature_FNN
    X_line_feature_FNN = np.zeros((Nsamples, Nline, 4))
    X_line_feature_FNN[:, :, 0] = X_pflow
    X_line_feature_FNN[:, :, 3] = np.tile(line_reactance, (Nsamples, 1))   # reactance

    for sample in range(Nsamples):
        ll = 0

        for l in range(Nline):

            if l not in line_outage_indices[sample]:
                X_line_feature_FNN[sample, l, 1] = X_line_feature_list[sample][ll, 1]   # ratio
                X_line_feature_FNN[sample, l, 2] = X_line_feature_list[sample][ll, 2]   # limit
                ll += 1

    # ==========================================================================
    # Initial congestion index
    # ==========================================================================

    # index
    X_pratio = X_line_feature_FNN[:, :, 1]   # X_pflow/x_limit         #Xratio can be an input feature

    overloaded_mask = np.abs(X_pratio) > ds_loading
    congestion_index = np.sum(((np.abs(X_pratio)) ** gamma) * overloaded_mask, axis=1)

    obj_ini = congestion_index   # [sample]

    # ==========================================================================
    # Final congestion index after candidate splitting
    # ==========================================================================

    obj_fin_list = []

    for sample in range(Nsamples):
        y_pratio = y_pflow_list[sample] / line_limit_list[sample]
        overloaded_mask = np.abs(y_pratio) > ds_loading   # [num_sw, nline]
        congestion_index = np.sum(
            ((np.abs(y_pratio)) ** gamma) * overloaded_mask,
            axis=1,
        )   # [num_sw]
        obj_fin_list.append(congestion_index)

    # ==========================================================================
    # Regression target generation
    # ==========================================================================

    delta_obj_list = []

    # clip_val = -1
    for i in range(Nsamples):
        delta = obj_ini[i] - obj_fin_list[i]   # obj_ini[i]: scalar, obj_fin_list[i]: [num_sw_i]
        if ForceSplit == False:
            delta[delta < 0] = 0   # remove negative values if needed
        # Clip values
        delta_clipped = np.clip(delta, a_min=clip_val, a_max=1000)   # [num_sw_i]
        # Reshape to [num_sw_i, 1] and store
        delta_obj_list.append(delta_clipped.reshape(-1, 1))

    Y_reg_list = delta_obj_list

    # ==========================================================================
    # Candidate-node filtering
    # ==========================================================================
    # filtering
    Y_reg_filtered = []
    bus_sw_indices_filtered = []

    for i in range(Nsamples):
        values = []
        indices = []
        for sw_ind, sw in enumerate(bus_sw_indices_list[i]):
            val = Y_reg_list[i][sw_ind]
            if 0 <= hops_list[i][sw] <= HopsFilter:   # filtering bad data
                values.append(val)
                indices.append(sw)
        Y_reg_filtered.append(np.array(values))
        bus_sw_indices_filtered.append(indices)
    Y_reg_list = Y_reg_filtered
    bus_sw_indices_list = bus_sw_indices_filtered

    # ==========================================================================
    # Classification labels
    # ==========================================================================

    # classification labels pos:good, neg:bad
    Y_clf_list = [(y > Clf_threshold).astype(np.int64) for y in Y_reg_list]

    # ==========================================================================
    # Homogeneous GNN target tensors and prediction mask
    # ==========================================================================

    # homo data
    Y_reg_homo = np.zeros((Nsamples, Nbus, 1))
    Y_clf_homo = np.zeros((Nsamples, Nbus, 1))
    prediction_mask = np.zeros((Nsamples, Nbus), dtype=bool)

    for s in range(Nsamples):
        for i, node_idx in enumerate(bus_sw_indices_list[s]):   # bus_sw_indices_list is a list of lists
            Y_reg_homo[s, node_idx, 0] = Y_reg_list[s][i, 0]
            Y_clf_homo[s, node_idx, 0] = Y_clf_list[s][i, 0]
            prediction_mask[s, node_idx] = True

    # ==========================================================================
    # Output dictionary
    # ==========================================================================

    # FinalDict
    Finaldict = {}

    Finaldict['X_bus_feature'] = X_bus_feature                 # [sample,bus,features]
    Finaldict['X_bus_sw_feature'] = X_bus_feature
    Finaldict['Y_reg_homo'] = Y_reg_homo
    Finaldict['Y_clf_homo'] = Y_clf_homo
    Finaldict['Y_reg_list'] = Y_reg_list
    Finaldict['Y_clf_list'] = Y_clf_list
    Finaldict['X_line_feature_list'] = X_line_feature_list     # list of [nline,N_line_features]
    Finaldict['X_line_feature_FNN'] = X_line_feature_FNN       # I use this for FNN
    Finaldict['Edge_sender_list'] = Edge_sender_list
    Finaldict['Edge_receiver_list'] = Edge_receiver_list
    Finaldict['bus_sw_indices_list'] = bus_sw_indices_list     # this is used for masking or node types
    Finaldict['prediction_mask'] = prediction_mask
    return Finaldict


