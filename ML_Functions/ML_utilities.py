def classification_metrics(
    preds,
    targets,
    probs=None,
    normalize=True
):
    """
    Compute binary classification metrics.

    Compute classification metrics including TP, TN, FP, FN, Accuracy,
    Precision, Recall, and F1 Score.
    Optionally normalize TP, TN, FP, FN to percentages.

    Args:
        preds (torch.Tensor): Binary predictions (0 or 1).
        targets (torch.Tensor): Ground truth binary labels (0 or 1).
        probs (torch.Tensor, optional): Predicted probabilities for positive class (0.0–1.0), for AUC calculation.
        normalize (bool): If True, TP, TN, FP, FN will be reported as percentages.

    Parameters
    ----------
    preds : torch.Tensor
        Binary predictions, typically thresholded to 0 or 1.
    targets : torch.Tensor
        Ground-truth binary labels.
    probs : torch.Tensor, optional
        Predicted probabilities for the positive class. Used for AUC.
    normalize : bool
        If True, report TP, TN, FP, and FN as percentages.

    Returns
    -------
    metrics : dict
        Dictionary of computed classification metrics.
    """

    # Apply sigmoid and threshold

    preds_bin = preds.detach().cpu().int()   # Assumes preds already thresholded #(torch.sigmoid(preds) > 0.5).int()
    targets = targets.detach().cpu().int()

    # === Confusion-matrix counts
    TP = ((preds_bin == 1) & (targets == 1)).sum().item()
    TN = ((preds_bin == 0) & (targets == 0)).sum().item()
    FP = ((preds_bin == 1) & (targets == 0)).sum().item()
    FN = ((preds_bin == 0) & (targets == 1)).sum().item()

    total = TP + TN + FP + FN

    # === Metrics
    metrics = {
        'TP': TP,
        'TN': TN,
        'FP': FP,
        'FN': FN,
        'Accuracy': (TP + TN) / total if total > 0 else 0,
        'Precision': TP / (TP + FP) if (TP + FP) > 0 else 0,
        'Recall': TP / (TP + FN) if (TP + FN) > 0 else 0,
        'F1 Score': 2 * TP / (2 * TP + FP + FN) if (2 * TP + FP + FN) > 0 else 0,
    }

    # Optionally add AUC if probabilities are provided
    if probs is not None:
        try:
            probs = probs.detach().cpu()
            metrics['AUC'] = float(roc_auc_score(targets.numpy(), probs.numpy()))
        except:
            metrics['AUC'] = float('nan')

    if normalize:
        # Convert counts to percentages of total
        for key in ['TP', 'TN', 'FP', 'FN']:
            metrics[f'{key} (%)'] = 100 * metrics[key] / total if total > 0 else 0
            del metrics[key]

    return metrics


