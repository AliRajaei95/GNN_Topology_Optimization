def train_val_test_split(
    num_samples=10000,
    split_ratios=[0.7, 0.15, 0.15],
    seed=0):
    """
    Split sample indices into training, validation, and test subsets.

    Parameters
    ----------
    num_samples : int
        Total number of samples.
    split_ratios : list
        Three-element list containing train, validation, and test ratios.
    seed : int
        Random seed used for reproducible shuffling.

    Returns
    -------
    train_indices : torch.Tensor
        Indices assigned to the training set.
    val_indices : torch.Tensor
        Indices assigned to the validation set.
    test_indices : torch.Tensor
        Indices assigned to the test set.
    """

    train_ratio = split_ratios[0]
    val_ratio = split_ratios[1]
    test_ratio = split_ratios[2]

    # Set random seed for reproducibility
    torch.manual_seed(seed)

    # Shuffle indices
    indices = torch.randperm(num_samples)

    # Compute split sizes
    train_size = int(train_ratio * num_samples)
    val_size = int(val_ratio * num_samples)

    # Split indices
    train_indices = indices[:train_size]
    val_indices = indices[train_size:train_size + val_size]
    test_indices = indices[train_size + val_size:]

    return train_indices, val_indices, test_indices


