class BoundaryAwareRegressionLoss(nn.Module):
    """
    Sign-aware regression loss for congestion-reduction prediction.

    This loss combines SmoothL1 regression loss with an optional penalty for
    sign mismatch between model outputs and targets. It can also assign higher
    weight to positive targets, which is useful when positive congestion
    reduction actions are more important than neutral or negative actions.

    Parameters
    ----------
    penalty_weight : float
        Weight applied to the sign-mismatch penalty.
    pos_weight : float
        Additional weight applied to positive regression targets.
    """

    def __init__(
        self,
        penalty_weight=0.0,
        pos_weight=0.0,
    ):
        """
        Initialize the boundary-aware regression loss.

        Parameters
        ----------
        penalty_weight : float
            Weight applied to the sign-mismatch penalty term.
        pos_weight : float
            Weight applied to samples with positive targets.
        """

        super().__init__()

        self.mse = nn.SmoothL1Loss()   # nn.MSELoss()
        self.penalty_weight = penalty_weight
        self.pos_weight = pos_weight   # how much more to weight positive targets

    def forward(
        self,
        outputs,
        targets,
    ):
        """
        Compute the weighted regression loss and sign-mismatch penalty.

        Parameters
        ----------
        outputs : torch.Tensor
            Model-predicted regression outputs.
        targets : torch.Tensor
            Ground-truth regression targets.

        Returns
        -------
        total_loss : torch.Tensor
            Combined regression and sign-mismatch loss.
        """

        # MSE loss
        base_loss = self.mse(outputs, targets)

        # Weight the regression loss based on the sign of the target
        # 1 if target ≤ 0, pos_weight if target > 0
        weights = torch.where(targets > 0, self.pos_weight, 1.0)

        weighted_loss = (base_loss * weights).mean()

        # Calculate sign mismatch:
        # When sign(outputs) != sign(targets) --> penalty applies
        sign_outputs = torch.sign(outputs)
        sign_targets = torch.sign(targets)

        # mismatch_mask = 1 where signs disagree, 0 where agree or zero target
        mismatch_mask = (sign_outputs != sign_targets).float()

        # Only penalize where target != 0 to avoid undefined sign issues #TODO?
        nonzero_target_mask = (targets != 0).float()

        penalty_mask = mismatch_mask * nonzero_target_mask

        # Penalty is proportional to magnitude of the prediction error where sign mismatch occurs
        penalty = (torch.abs(outputs - targets) * penalty_mask).mean()

        # Total loss = regression loss + weighted penalty for sign mismatch
        total_loss = weighted_loss + self.penalty_weight * penalty

        return total_loss


