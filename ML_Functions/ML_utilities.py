"""
Feature-preparation utilities for ML-based optimal substation switching.

This module prepares node, edge, and target-label features for different
machine-learning models used in power-system congestion management and
busbar-splitting studies.

The implementations include:
    - GNN-ready node and edge feature construction
    - FNN-ready fixed-size line-feature construction
    - Regression and classification label generation
    - Prediction masks for candidate switching nodes
    - Custom regression loss for sign-aware learning
    - Classification metric evaluation
    - Train/validation/test splitting utilities
    - Diagnostic plotting functions for regression and classification outputs

The generated features are intended for supervised learning, graph neural
networks (GNNs), feed-forward neural networks (FNNs), and ML-assisted
topology-control studies.

"""

