def plot_prediction_scatter_reg(
    pred,
    target):
    """
    Plot regression predictions against target values.

    Scatter plot of predictions vs targets with color indicating MSE error.

    Args:
        pred (array-like): Predicted values.
        target (array-like): Ground truth target values.

    Parameters
    ----------
    pred : array-like
        Predicted regression values.
    target : array-like
        Ground-truth regression values.
    """

    # Compute squared error for coloring
    mse_error = (pred - target) ** 2

    print("mse error is: %.5f " % np.mean(mse_error))

    # Scatter plot
    plt.figure(figsize=(5, 4))

    scatter = plt.scatter(
        target,
        pred,
        c=mse_error,
        cmap='coolwarm',
        alpha=0.5,
        s=5,
    )

    cbar = plt.colorbar(scatter)
    cbar.set_label('Squared Error')
    cbar.ax.yaxis.set_major_formatter(FormatStrFormatter('%.2f'))

    # Reference lines
    min_val = min(target.min(), pred.min())
    max_val = max(target.max(), pred.max())

    plt.plot([min_val, max_val], [min_val, max_val], 'k--', label='y = x')   # y = x line
    plt.axhline(0, color='gray', linestyle='--')                             # y = 0
    plt.axvline(0, color='gray', linestyle='--')                             # x = 0

    plt.xlabel('Target')
    plt.ylabel('Prediction')
    plt.title('Prediction vs Target with Error Coloring')

    # plt.legend()

    plt.grid(True)
    plt.tight_layout()
    plt.show()


